# @data-structure-type: seg-tree
# @complexities:
#   getAll: N
#   leftmostGtX: log(N)
#   leftmostGteX: log(N)
#   pointAssign: log(N)
#   pointChmax: log(N)
#   pointChmin: log(N)
#   pointGet: log(N)
#   rangeMax: log(N)
#   rightmostGtX: log(N)
#   rightmostGteX: log(N)
#   maxAll: log(N)
#   build: N
# @memory:
#   layout: 2n-iterative
#   node: sm[2*N] mx[2*N] pre[2*N] nsuf[2*N]
