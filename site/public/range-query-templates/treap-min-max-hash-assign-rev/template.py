    # O(logN) expected -- the last i in [l, r] with a[i] <= x, or -1: a walk down a[l..r]'s tree, pruned by the
    # subtree min
    def rightmostLteX(self, l, r, x):
        a, b, c = self._cut(l, r)
        L, R, val, sz, F = self.L, self.R, self.val, self.sz, self.mn
