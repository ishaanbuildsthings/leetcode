// @data-structure-type: lazy-seg-tree
// @complexities:
//   getAll: N
//   leftmostLtX: log(N)
//   leftmostLteX: log(N)
//   maxAltSubseqSum: log(N)
//   pointAdd: log(N)*log(U) ?
//   pointAssign: log(N)*log(U) ?
