// Reads the tree query templates in ../templates/ultimate-template-tool/tree-queries (written by the generators in
// tree-query-tests/) and generates:
//   - lib/generated/tree-query-templates.ts  (the manifest the Tree queries tab's picker reads)
//   - public/tree-query-templates/<folder>/template.{py,cpp}  (the copies the picker's drawer fetches)
//
// Each folder holds template.py and template.cpp (the C++ one is fast mode by default: there is no fast.cpp) with the
// same header as the range-query and set templates. Run with: npm run gen:tree-queries

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LANGS, readHeaderFile, readUsage } from "./catalog-lib.mjs";

const siteDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.resolve(siteDir, "../templates/ultimate-template-tool/tree-queries");
const publicDir = path.join(siteDir, "public/tree-query-templates");
const manifestPath = path.join(siteDir, "lib/generated/tree-query-templates.ts");

const TAGS = ["operations", "data-structure-type", "complexities", "memory"];
// (the same list, in the same order, as TREE_STRUCTURE_TYPES in lib/tree-query-picker.ts)
const TYPES = [
  "heavy-light", "heavy-light-lca-table",
  // a value template is named for the range structure it keeps the values in (the range picker's types)
  "prefix-sum", "difference-array", "positions", "interval-map", "sparse-table", "BIT", "seg-tree", "lazy-seg-tree", "beats",
  "merge-sort-tree", "wavelet", "persistent", "bit-of-trees", "bit-of-tries", "seg-of-trees", "position-trees", "sqrt",
  "sqrt-tries",
  // structures of the tree templates' own (no range template inside)
  "euler-fenwick", "persistent-paths", "bitset-seg-tree", "run-seg-tree", "root-prefix",
];

const errors = [];
const entries = [];

for (const folder of fs.readdirSync(srcDir).sort()) {
  const folderPath = path.join(srcDir, folder);
  if (!fs.statSync(folderPath).isDirectory()) continue;
  const langs = [];
  let data = null;
  for (const [ext, lang] of Object.entries(LANGS)) {
    const filePath = path.join(folderPath, `template${ext}`);
    if (!fs.existsSync(filePath)) continue;
    const where = `${folder}/template${ext}`;
    const { errs, data: d } = readHeaderFile(where, filePath, { tags: TAGS });
    errors.push(...errs);
    if (!TYPES.includes(d.dataStructureType)) errors.push(`${where}: @data-structure-type must be one of ${TYPES.join(", ")}`);
    // (the drawer reads usage from the code itself; this only checks it can)
    if (!readUsage(fs.readFileSync(filePath, "utf8"), lang, d.operations)) errors.push(`${where}: no class implements every operation (needed for the usage panel)`);
    langs.push(lang);
    if (!data) data = d;
    else if (JSON.stringify(data) !== JSON.stringify(d)) errors.push(`${folder}: template${ext} header disagrees with the other language's`);
  }
  for (const f of fs.readdirSync(folderPath).filter((f) => f !== "__pycache__"))  // Python's cache from running tests
    if (!Object.keys(LANGS).some((ext) => f === `template${ext}`)) errors.push(`${folder}: unexpected file ${f}`);
  if (!data) {
    errors.push(`${folder}: no template.py or template.cpp`);
    continue;
  }
  entries.push({ folder, langs, ...data });
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

fs.rmSync(publicDir, { recursive: true, force: true });
for (const { folder, langs } of entries) {
  fs.mkdirSync(path.join(publicDir, folder), { recursive: true });
  for (const l of langs) fs.copyFileSync(path.join(srcDir, folder, `template.${l}`), path.join(publicDir, folder, `template.${l}`));
}

// Hundreds of variants share a few op lists, cost strings and memory layouts: the manifest is those tables plus one
// short row per template, expanded in the browser by decodeTreeQueryTemplates (lib/tree-query-picker.ts).
const table = () => {
  const items = [];
  const index = new Map();
  return {
    items,
    id(key, item = key) {
      if (!index.has(key)) index.set(key, items.push(item) - 1);
      return index.get(key);
    },
  };
};
const costs = table();
const opLists = table();
const memories = table();
const rows = entries.map((e) => [
  e.folder,
  e.langs.join(" "),
  e.dataStructureType,
  opLists.id(e.operations.join(" "), e.operations),
  e.operations.map((op) => costs.id(e.complexities[op])),
  costs.id(e.build),
  memories.id(JSON.stringify(e.memory), e.memory),
]);

const manifest = `// Generated by scripts/build-tree-query-templates.mjs from templates/ultimate-template-tool/tree-queries. Do not edit.
import type { TreeQueryManifest } from "@/lib/tree-query-picker";

export const TREE_QUERY_MANIFEST: TreeQueryManifest = {
  costs: ${JSON.stringify(costs.items)},
  opLists: ${JSON.stringify(opLists.items)},
  memories: ${JSON.stringify(memories.items)},
  rows: [
${rows.map((r) => `    ${JSON.stringify(r)},`).join("\n")}
  ],
};
`;
fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
fs.writeFileSync(manifestPath, manifest);
console.log(`${entries.length} tree query templates -> ${path.relative(siteDir, manifestPath)} + ${path.relative(siteDir, publicDir)}/`);
